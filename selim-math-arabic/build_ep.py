def stage_lengths():
    total = 0
    for cid, title, text in CLIPS:
        n = len(text)
        total += n
        flag = "OK " if n <= 1450 else "TOO LONG!!"
        print(f"clip {cid} ({title}): {n} chars {flag}")
    print(f"total: {total} chars ≈ {total/10.6/60:.1f} min speech")


def ff():
    import imageio_ffmpeg
    return imageio_ffmpeg.get_ffmpeg_exe()


def make_silence(path, seconds=0.9):
    F = ff()
    subprocess.run([F, '-y', '-f', 'lavfi', '-i', 'anullsrc=r=24000:cl=mono',
                    '-t', str(seconds), '-q:a', '9', '-acodec', 'libmp3lame', path],
                   check=True, capture_output=True)


def stage_audio():
    os.makedirs(AUD, exist_ok=True)
    F = ff()
    ids = [c[0] for c in CLIPS]
    for cid in ids:
        p = os.path.join(AUD, f'clip{cid}.mp3')
        assert os.path.isfile(p), f"missing {p}"
    parts = os.path.join(HERE, 'parts')
    os.makedirs(parts, exist_ok=True)
    sil = os.path.join(parts, 'sil.mp3')
    make_silence(sil, 0.9)
    lst = os.path.join(parts, 'list.txt')
    with open(lst, 'w', encoding='utf-8') as f:
        for i, cid in enumerate(ids):
            if i:
                f.write(f"file '{sil}'\n")
            f.write(f"file '{os.path.join(AUD, f'clip{cid}.mp3')}'\n")
    subprocess.run([F, '-y', '-f', 'concat', '-safe', '0', '-i', lst,
                    '-ar', '24000', '-ac', '1', '-b:a', '32k', FINAL_MP3],
                   check=True, capture_output=True)
    out = subprocess.run([F, '-i', FINAL_MP3], capture_output=True).stderr.decode(
        'utf-8', 'ignore')
    import re
    m = re.search(r'Duration: (\d+):(\d+):(\d+\.\d+)', out)
    sz = os.path.getsize(FINAL_MP3)
    if m:
        h, mm, ss = int(m.group(1)), int(m.group(2)), float(m.group(3))
        print(f"FINAL MP3: {FINAL_MP3} | {h*60+mm}:{int(ss):02d} | {sz/1e6:.2f} MB")
    else:
        print(f"FINAL MP3: {FINAL_MP3} | {sz/1e6:.2f} MB")


def _rtl(p):
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    from docx.oxml.ns import qn
    from docx.oxml import OxmlElement
    p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    pPr = p._p.get_or_add_pPr()
    bidi = OxmlElement('w:bidi')
    bidi.set(qn('w:val'), '1')
    pPr.append(bidi)


def stage_docx():
    from docx import Document
    from docx.shared import Pt, RGBColor
    doc = Document()
    st = doc.styles['Normal']
    st.font.name = 'Arial'
    st.font.size = Pt(12)

    def head(txt, size=16, color=(0x8A, 0x1C, 0x1C)):
        p = doc.add_paragraph()
        _rtl(p)
        r = p.add_run(txt)
        r.bold = True
        r.font.size = Pt(size)
        r.font.color.rgb = RGBColor(*color)

    def para(txt, bold=False):
        p = doc.add_paragraph()
        _rtl(p)
        r = p.add_run(txt)
        r.bold = bold

    head('حلقة سليم: خواص الضرب (الجزء الثاني) — تجزئة المضروب', 18)
    head('«رحلة سر التقسيم السحري» — سيناريو الحلقة الصوتية', 14, (0x1F, 0x4E, 0x79))
    para('الدرس: ١-٢ خواص الضرب (الجزء الثاني) — الفصل الأول: قواعد الضرب — رياضيات الصف الثالث الابتدائي')
    para('الأبطال: سليم (٨ سنوات)، كرمة (٥ سنوات — العدّ والترديد)، كندا (سنتان — الضحك والتصفيق)')
    para('القاعدة الذهبية: الرقم الكبير نقسّمه لحاجتين سهلين، نضرب كل واحدة، ونجمع — والناتج دائمًا نفسه.')
    doc.add_paragraph()

    for cid, title, text in CLIPS:
        head(f'المقطع {int(cid)}: {title}', 13, (0x2E, 0x6B, 0x2E))
        for chunk in text.split('\n'):
            para(chunk)
        doc.add_paragraph()

    head('واجب النجوم (مع الحلول للماما والبابا)', 15)
    for q, a in HOMEWORK:
        para('❓ ' + q, bold=True)
        para('✅ الحل: ' + a)

    doc.add_paragraph()
    head('ملاحظات تربوية للكبار', 14, (0x1F, 0x4E, 0x79))
    for t in [
        'الخاصية مستندة لدرس الكتاب: يمكن كتابة مكونات المضروب عند الضرب ويكون الناتج نفسه.',
        'شجّعوا سليم أن يختار «الفكّة» الأسهل له (جدول ٥ و٤ أسهل له الآن) — القطة في الكتاب تقول: لديك اختيارات كثيرة.',
        'الوقفات داخل الحلقة مصممة ليجيب الطفل بصوت عالٍ؛ العد مع كرمة يعطي وقتًا حقيقيًا للتفكير.',
        'النجمة الذهبية (٤ × ١٢) تُظهر أن الخاصية تعمل مع أعداد لم يحفظ جدولها بعد.',
    ]:
        para('• ' + t)

    doc.save(FINAL_DOCX)
    print(f"FINAL DOCX: {FINAL_DOCX} | {os.path.getsize(FINAL_DOCX)/1e3:.1f} KB")


if __name__ == '__main__':
    stage = sys.argv[1] if len(sys.argv) > 1 else 'lengths'
    {'lengths': stage_lengths, 'audio': stage_audio, 'docx': stage_docx}[stage]()
